/**
 * Filter formulas by time window.
 */
export function getFormulasByTimeWindow(window: string): Formula[] {
  return FORMULAS.filter((f) => f.time_window === window);
}

/**
 * Filter formulas by dietary restrictions.
 * Returns formulas that do NOT contain any excluded allergens.
 */
export function filterFormulasByDiet(formulas: Formula[], diet: string): Formula[] {
  if (diet === 'none') return formulas;

  const excluded: string[] = [];
  if (diet === 'gluten-free' || diet === 'all-free') excluded.push('Gluten');
  if (diet === 'dairy-free' || diet === 'all-free') excluded.push('Dairy');
  if (diet === 'peanut-free' || diet === 'all-free') excluded.push('Peanut');

  return formulas.filter((f) =>
    !f.allergens.some((a) => excluded.includes(a))
  );
}
