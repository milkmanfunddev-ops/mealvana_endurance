export async function handleSendEmail(
  req: Request,
  deps: SendEmailDeps = {},
): Promise<Response> {
  if (req.method === 'OPTIONS') {
    return new Response('ok', { headers: corsHeaders });
  }

  const auth = deps.authenticate ?? authenticate;
  const doFetch = deps.fetchFn ?? fetch;
  // Read from the RESEND_API_KEY Supabase secret (set on dev+prod 2026-07-01;
  // value also in secrets/resend.env). No hardcoded fallback — a missing secret
  // should surface as a Resend 401, not silently use a stale key.
  const apiKey = deps.apiKey ?? Deno.env.get('RESEND_API_KEY') ?? '';

  // Caller check first: no body is read and no mail is sent for a stranger.
  const result = await auth(req);
  if (!result.ok) {
    return json({ success: false, error: result.error }, result.status);
  }

  try {
    const { recipientEmail, senderName, subject, comments, pdfAttachment }: EmailPayload =
      await req.json();

    if (!recipientEmail) {
      return json({ success: false, error: 'Recipient email is required' }, 400);
    }
    if (!pdfAttachment) {
      return json({ success: false, error: 'PDF attachment is required' }, 400);
    }

    const emailHtml = buildEmailHtml(senderName, comments);

    const resendResponse = await doFetch(RESEND_API_URL, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${apiKey}`,
      },
      body: JSON.stringify({
        from: FROM_EMAIL,
        to: recipientEmail,
        subject: subject || DEFAULT_SUBJECT,
        html: emailHtml,
        attachments: [{ filename: 'nutrition-plan.pdf', content: pdfAttachment }],
      }),
    });

    const resendData = await resendResponse.json();

    if (!resendResponse.ok) {
      console.error('Resend API error:', resendData);
      return json(
        { success: false, error: resendData.message || 'Failed to send email' },
        resendResponse.status,
      );
    }

    return json(
      { success: true, message: 'Email sent successfully', emailId: resendData.id },
      200,
    );
  } catch (error) {
    console.error('Error sending email:', error);
    return json(
      {
        success: false,
        error: error instanceof Error ? error.message : 'Unknown error occurred',
      },
      500,
    );
  }
}
