/**
 * send-nutrition-plan-email — request handler.
 *
 * Split out of `index.ts` so the real handler can be exercised in tests without
 * `serve()` binding a port. `index.ts` is now the thin wiring file.
 *
 * Auth: a signed-in caller is required (ai-cost ticket 01, mp-466). The app already
 * sends the Supabase user JWT on `functions.invoke`. Without a valid token the
 * function returns 401 and sends nothing — the Resend call is never made.
 */
import { authenticate } from '../_shared/vana/auth.ts';

export const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
};

const FROM_EMAIL = 'support@mealvana.io';
const DEFAULT_SUBJECT = 'Your Nutrition Plan from Mealvana Endurance';
const RESEND_API_URL = 'https://api.resend.com/emails';

/** Only the shape this handler needs — the shared helper returns more. */
type AuthOutcome = { ok: true } | { ok: false; status: number; error: string };

export interface SendEmailDeps {
  /** Caller check. Defaults to the shared `_shared/vana/auth.ts` helper. */
  authenticate?: (req: Request) => Promise<AuthOutcome>;
  /** Outbound HTTP, so tests never reach Resend. */
  fetchFn?: typeof fetch;
  /** Resend API key. Defaults to the RESEND_API_KEY secret. */
  apiKey?: string;
}

export interface EmailPayload {
  recipientEmail?: string;
  senderName?: string;
  subject?: string;
  comments?: string;
  pdfAttachment?: string;
}

function json(body: unknown, status: number): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...corsHeaders, 'Content-Type': 'application/json' },
  });
}

