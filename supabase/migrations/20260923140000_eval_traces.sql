-- eval_traces: the durable home for full Vana turn traces (evals/vana/README.md is the system's front door).
-- Written only by the evals loader (service role) today; opt-in sampling of real turns will land here later with
-- source='real'. Deliberately OUTSIDE ai_log_retention_sweep's reach — the sweep empties vana_calls / ai_usage /
-- plan_generation_log after 90 days, and an eval corpus must outlive that (the sweep names its tables explicitly).
-- RLS on, no policies: only the service role reads or writes it. Human-authored artefacts (scenarios, annotations)
-- live in the repo; this table is the bulk machine-written layer (Lee, 2026-09-23).

create table if not exists public.eval_traces (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  -- 'synthetic' = generated by the harness; 'real' = sampled production turn (future).
  source text not null default 'synthetic' check (source in ('synthetic', 'real')),
  -- Which harness run produced the row (traces regenerate per run; run_id groups them).
  run_id text not null,
  -- The tuple the scenario was drawn from (generate-synthetic-data skill, step 1). Nullable on real traces.
  scenario_id text,
  task text,
  athlete text,
  character text,
  -- Turn number within the scenario's conversation (1-based).
  turn int not null default 1,
  model text,
  input_tokens int,
  output_tokens int,
  cache_read_tokens int,
  duration_ms int,
  error text,
  -- The full TurnTrace payload from _shared/vana/chat.ts onTrace: persona, Doll, situation, model messages,
  -- tools offered, per-step tool inputs/outputs and raw text, usage.
  payload jsonb not null
);

alter table public.eval_traces enable row level security;

create index if not exists eval_traces_source_created_idx on public.eval_traces (source, created_at desc);
create index if not exists eval_traces_scenario_idx on public.eval_traces (scenario_id, run_id, turn);
